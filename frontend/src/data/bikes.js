export function getBikeById(id) {
  return bikes.find((b) => b.id === id) || null;
}

export function getFeaturedBikes() {
  return bikes.filter((b) => b.featured);
}

export function getBikesByCategory(category) {
  if (!category || category === 'all') return bikes;
  return bikes.filter((b) => b.category === category);
}
